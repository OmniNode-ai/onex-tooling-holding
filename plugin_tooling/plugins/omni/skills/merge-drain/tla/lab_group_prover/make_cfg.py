#!/usr/bin/env python3
"""Generate cfg/*.cfg for LabGroupProver.tla (OMN-18893). Each config names only what it changes."""
from pathlib import Path

BASE = {
    "PRs": "{p1, p2, p3}", "MaxHead": "2", "NONE": "NONE", "Bad": "{}", "Interact": "{}",
    "UsePrefix": "TRUE", "ReleaseRule": '"confirmed"', "FailSuppress": "TRUE", "AppendPassedOnly": "TRUE",
    "BPush": "0", "BHold": "0", "BClose": "0", "BCrash": "0", "BPDie": "0", "BInc": "0",
    "BNoHost": "0", "BExpire": "0", "Track": "FALSE",
}
SAFETY = "Safety"
CFGS = {
    # verification, safety
    "V_bad": dict(inv=SAFETY, Bad="{p3}", BPush="1", BHold="1", BCrash="1", BPDie="1", BInc="1", BNoHost="1", BExpire="1"),
    "V_interact": dict(inv=SAFETY, Interact="{{p1, p2}}", BPush="1", BHold="1", BCrash="1", BPDie="1", BNoHost="1", BExpire="1"),
    "V_mixed": dict(inv=SAFETY, Bad="{p1}", Interact="{{p2, p3}}", BPush="1", BHold="1", BClose="1", BCrash="1", BPDie="1", BInc="1"),
    "V_triple": dict(inv=SAFETY, Interact="{{p1, p2, p3}}", BHold="1", BCrash="1", BPDie="1", BNoHost="1", BExpire="1"),
    # verification, liveness
    "L_bad": dict(spec="LiveSpec", inv=SAFETY, prop="Progress", Bad="{p3}", BPush="1", BCrash="1", BPDie="1", BInc="1", BNoHost="1", BExpire="1"),
    "L_interact": dict(spec="LiveSpec", inv=SAFETY, prop="Progress", Interact="{{p1, p2}}", BPush="1", BHold="1", BCrash="1", BPDie="1", BNoHost="1"),
    # positive control for liveness: no fairness, Progress MUST be violated (stuttering)
    "M_live_no_fairness": dict(spec="Spec", inv=SAFETY, prop="Progress", Interact="{{p1, p2}}"),
    # mutations: each flips one guard and MUST violate the named property
    "M_no_prefix": dict(inv="NoLatentBreak", UsePrefix="FALSE", Interact="{{p1, p2}}"),
    "M_release_on_result": dict(inv="OneProver ProverLeased", ReleaseRule='"result"', Bad="{p3}", BPush="1"),
    "M_no_fail_suppress": dict(inv="NoFailReprove", FailSuppress="FALSE", Bad="{p3}", BPush="1"),
    "M_append_failed": dict(inv="NoUnprovenReadback", AppendPassedOnly="FALSE", Bad="{p3}"),
    # scenarios: Track=TRUE, NotS<n> must be violated (reachability, Safety on every state)
    "S_group_pass": dict(inv=f"{SAFETY} NotGroupPass", Track="TRUE"),
    "S_bisect": dict(inv=f"{SAFETY} NotBisect", Track="TRUE", Bad="{p3}"),
    "S_half_pass": dict(inv=f"{SAFETY} NotHalfPassAfterFail", Track="TRUE", Bad="{p3}"),
    "S_interaction": dict(inv=f"{SAFETY} NotBlamedByInteraction", Track="TRUE", Interact="{{p1, p2}}"),
    "S_crash": dict(inv=f"{SAFETY} NotRespawnAfterCrash", Track="TRUE", BCrash="1"),
    "S_head_moved": dict(inv=f"{SAFETY} NotHeadMoved", Track="TRUE", BPush="1"),
}

out = Path(__file__).parent / "cfg"
out.mkdir(exist_ok=True)
for name, over in CFGS.items():
    o = dict(over)
    spec, inv, prop = o.pop("spec", "Spec"), o.pop("inv"), o.pop("prop", None)
    consts = {**BASE, **o}
    lines = [f"\\* generated by make_cfg.py {name}", f"SPECIFICATION {spec}", "CONSTANTS"]
    lines += [f"  {k} = {v}" for k, v in consts.items()]
    lines += [f"INVARIANT {i}" for i in inv.split()]
    if prop:
        lines.append(f"PROPERTY {prop}")
    (out / f"{name}.cfg").write_text("\n".join(lines) + "\n")
print(" ".join(CFGS))
