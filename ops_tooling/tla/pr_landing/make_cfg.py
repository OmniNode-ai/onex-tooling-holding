#!/usr/bin/env python3
"""make_cfg.py <name> <EnvBudget> "<invariants>" [KEY=VAL ...]: writes <name>.cfg.
The baseline is revision 1 (F1-F10 on) plus the proposed revision-2 values for G1-G4."""

import sys

name, eb, inv, *kv = sys.argv[1:]
NONTERM = [
    "OBSERVED",
    "COMPANION_PENDING",
    "COMPANION_OPEN",
    "CHECKS_PENDING",
    "READY",
    "ARMED",
    "NEEDS_AGENT",
]
C = dict(
    HeadDrop="TRUE",
    OrderedHead="TRUE",
    SeqGuard="TRUE",
    HoldAnyState="TRUE",
    CompInflight="TRUE",
    CompOutcomeExempt="TRUE",
    OutboxSupersede="TRUE",
    RunAttempt="TRUE",
    OCC="TRUE",
    Lease="TRUE",
    AtLeastOnce="FALSE",
    EffectIdem="TRUE",
    Timers="TRUE",
    Reopen="FALSE",
    Declines="TRUE",
    Dups="1",
    TimerBudget="1",
    Atomic="TRUE",
    Foreign="FALSE",
    Checks="TRUE",
    ClosedIngress='"flag"',
    CcLag="TRUE",
    CcOpenRow='"pending"',
    StallTimer="FALSE",
    TimerTagged="TRUE",
    NewHeadArm='"keep"',
    ReopenEval="TRUE",
    ClosedCompanion="TRUE",
    ClosedNewer="TRUE",
    ClosedSeq="TRUE",
    ClosedMerged="TRUE",
    BoundStates="{" + ", ".join(f'"{s}"' for s in NONTERM) + "}",
)
spec, sym, prs, props, wks = "Spec", True, "{p1, p2}", "", "{w1, w2}"
for x in kv:
    k, _, v = x.partition("=")
    if k == "SPEC":
        spec = v
    elif k == "NOSYM":
        sym = False
    elif k == "PRS":
        prs = v
    elif k == "PROPS":
        props = v
    elif k == "BOUND_PARKED":
        C["BoundStates"] = "{" + ", ".join(f'"{s}"' for s in [*NONTERM, "PARKED"]) + "}"
    elif k in ("ClosedIngress", "CcOpenRow", "NewHeadArm"):
        C[k] = f'"{v}"'
    else:
        C[k] = v
out = [
    f'\\* generated by make_cfg.py {name} {eb} "{inv}" {" ".join(kv)}',
    "CONSTANTS",
    f"  PRs = {prs}",
    f"  Workers = {wks}",
    "  MaxHead = 2",
    f"  EnvBudget = {eb}",
    "  Nil = Nil",
]
out += [f"  {k} = {v}" for k, v in C.items()]
out.append(f"SPECIFICATION {spec}")
if inv:
    out.append(f"INVARIANTS {inv}")
if props:
    out.append(f"PROPERTIES {props}")
if sym:
    out.append("SYMMETRY Sym")
with open(f"{name}.cfg", "w") as fh:
    fh.write("\n".join(out) + "\n")
