#!/usr/bin/env python3
"""make_cfg.py <name> [KEY=VAL ...]: writes cfg/<name>.cfg for LandingController.tla.

Every constant starts at the plan's value (revision 4 as written) with every
environment budget at 0; a config names only what it changes. Special keys:
SPEC (default Spec), INV (space-separated invariants), PROPS (temporal
properties), SYM (a symmetry set, SymW or SymPW; safety configs only)."""

import sys
from pathlib import Path

C = dict(
    PRs="{p1, p2}",
    Workers="{w1, w2}",
    Nil="Nil",
    Collab="{}",
    Runtime="{}",
    MaxHead="2",
    Engines="2",
    MaxDispatch="2",
    MaxAttempts="3",
    MaxComps="4",
    InitCi='"red"',
    InitComp="FALSE",
    PushModes='{"ff", "fwl"}',
    ResultKinds='{"fix_submitted", "external_blocker", "waiting_ci"}',
    BPush="0",
    BForeign="0",
    BMPush="0",
    BClose="0",
    BElig="0",
    BBlk="0",
    BCrash="0",
    BPFail="0",
    BDrain="0",
    Track="FALSE",
    LeaseByPR="TRUE",
    ReleaseRule='"term"',
    DiscardRevoked="TRUE",
    Verify='"evidence"',
    PinMerge="TRUE",
    FreeTokenFirst="TRUE",
    MemberElig="TRUE",
    WaitOnSuspended="TRUE",
    BlockedSuppress="TRUE",
    SuppressAny="FALSE",
    DrainGate="TRUE",
    ProducerIdem="TRUE",
    RedeliverPending="TRUE",
    RetryFailed="TRUE",
    Cover="TRUE",
    SeenAny="TRUE",
    # the red-PR fixer (OMN-20414); Repos defaults to one repo holding every PR
    Repos=None,
    Causes="{}",
    Members="{}",
    Budget="2",
    RepoCap="6",
    CauseRepoCap="2",
    CauseFleetCap="4",
    CauseKinds='{"cause_fix_submitted", "cause_not_shared", "external_blocker"}',
    BHold="0",
    BClaim="0",
    BCClaim="0",
    BPark="0",
    MemberSuppress="TRUE",
    BudgetGate="TRUE",
    HoldGate="TRUE",
    CapGate="TRUE",
    EscDedupe='"ledger"',
    MemberClaimsOwn="FALSE",
    LateExitCounts="TRUE",
    # the bus owner (OMN-20744, retirement plan S2); off unless a config turns it on
    BusOn="FALSE",
    BusAct="TRUE",
    BRestart="0",
    BusDurable="TRUE",
    BusAbsorb="TRUE",
    BusCas="TRUE",
)

name, *kv = sys.argv[1:]
spec, inv, props, sym = "Spec", "", "", ""
for x in kv:
    k, _, v = x.partition("=")
    if k == "SPEC":
        spec = v
    elif k == "INV":
        inv = v
    elif k == "PROPS":
        props = v
    elif k == "SYM":
        sym = v
    elif k in C:
        C[k] = v
    else:
        sys.exit(f"unknown constant {k}")

if C["Repos"] is None:
    C["Repos"] = "{" + C["PRs"] + "}"
lines = [f"\\* generated by make_cfg.py {' '.join([name, *kv])}", "CONSTANTS"]
lines += [f"  {k} = {v}" for k, v in C.items()]
lines.append(f"SPECIFICATION {spec}")
if inv:
    lines.append(f"INVARIANTS {inv}")
if props:
    lines.append(f"PROPERTIES {props}")
if sym:
    lines.append(f"SYMMETRY {sym}")
out = Path(__file__).parent / "cfg" / f"{name}.cfg"
out.parent.mkdir(exist_ok=True)
out.write_text("\n".join(lines) + "\n")
